"""**Reasoning**:
Load the model-ready dataset, perform a chronological split to prevent temporal leakage, scale features strictly on training data, train a baseline Random Forest classifier, and print evaluation metrics (ROC-AUC, PR-AUC, F1-score) along with a summary of the performance.


"""

import pandas as pd
import numpy as np
from sklearn.preprocessing import StandardScaler
from sklearn.ensemble import RandomForestClassifier
from sklearn.metrics import roc_auc_score, precision_recall_curve, auc, f1_score, classification_report

def run_ml_pipeline():
    print("=== Starting Phase 10: Machine Learning Pipeline ===\n")

    # 1. Load dataset
    df = pd.read_parquet('/content/model_ready_dataset.parquet')
    print(f"Loaded dataset with shape: {df.shape}")

    # 2. Chronological Sorting to prevent temporal leakage
    df = df.sort_values(by='prediction_timestamp').reset_index(drop=True)

    # 3. Define target and drop non-predictive columns
    y = df['label']
    X = df.drop(columns=['session_id', 'visitorid', 'itemid', 'prediction_timestamp', 'converted', 'label'])

    # Identify features to scale
    feature_names = X.columns.tolist()
    print(f"Predictive Features ({len(feature_names)}): {feature_names}")

    # 4. Chronological Train-Test Split (80% Train, 20% Validation)
    split_idx = int(len(df) * 0.8)
    X_train, X_val = X.iloc[:split_idx], X.iloc[split_idx:]
    y_train, y_val = y.iloc[:split_idx], y.iloc[split_idx:]

    print(f"Train size: {X_train.shape[0]} ({X_train.shape[0]/len(df)*100:.1f}%)")
    print(f"Val size: {X_val.shape[0]} ({X_val.shape[0]/len(df)*100:.1f}%)")

    # 5. Feature Scaling (Fit on Train only, transform both)
    scaler = StandardScaler()
    X_train_scaled = scaler.fit_transform(X_train)
    X_val_scaled = scaler.transform(X_val)

    # 6. Train Baseline Classifier (Random Forest with class balancing)
    model = RandomForestClassifier(n_estimators=100, random_state=42, class_weight='balanced', n_jobs=-1)
    model.fit(X_train_scaled, y_train)
    print("\nBaseline RandomForestClassifier trained successfully.")

    # 7. Predict and Evaluate
    y_pred = model.predict(X_val_scaled)
    y_prob = model.predict_proba(X_val_scaled)[:, 1]

    # Calculate Metrics
    roc_auc = roc_auc_score(y_val, y_prob)
    precision, recall, _ = precision_recall_curve(y_val, y_prob)
    pr_auc = auc(recall, precision)
    f1 = f1_score(y_val, y_pred)

    print("\n=== Baseline Evaluation Metrics ===")
    print(f"ROC-AUC Score:         {roc_auc:.4f}")
    print(f"PR-AUC Score:          {pr_auc:.4f}")
    print(f"F1 Score (Threshold 0.5): {f1:.4f}")

    print("\nClassification Report:")
    print(classification_report(y_val, y_pred))

    # Print Feature Importances
    importances = pd.Series(model.feature_importances_, index=feature_names).sort_values(ascending=False)
    print("\nTop Predictive Features by Importance:")
    for idx, (feat, imp) in enumerate(importances.items()):
         print(f"  {idx+1}. {feat:<26} : {imp:.4f}")

run_ml_pipeline()

