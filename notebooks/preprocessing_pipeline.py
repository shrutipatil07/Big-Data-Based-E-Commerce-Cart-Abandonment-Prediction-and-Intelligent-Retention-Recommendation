import pandas as pd
import numpy as np

def engineer_features():
    print("=== Starting Phase 6: Feature Engineering at Prediction Time ===")

    # 1. Load data
    labeled_path = '/content/labeled_cart_units.csv'
    sessionized_path = '/content/sessionized_events.csv'

    print(f"Loading labeled units from {labeled_path}...")
    labeled_df = pd.read_csv(labeled_path)

    print(f"Loading sessionized events from {sessionized_path}...")
    events_df = pd.read_csv(sessionized_path)

    # Convert timestamps explicitly
    labeled_df['prediction_timestamp'] = labeled_df['prediction_timestamp'].astype(np.int64)
    events_df['timestamp'] = events_df['timestamp'].astype(np.int64)

    # Pre-sort events chronologically
    events_df = events_df.sort_values(by=['visitorid', 'timestamp']).reset_index(drop=True)

    # 2. To avoid leakage and do this efficiently, we will merge events and labeled units on visitorid
    # and filter for events that happened *prior to or equal to* the prediction_timestamp
    print("Merging events with prediction timestamps to filter history...")
    merged = pd.merge(
        labeled_df[['session_id', 'visitorid', 'itemid', 'prediction_timestamp']],
        events_df[['visitorid', 'session_id', 'event', 'itemid', 'timestamp']],
        on='visitorid',
        suffixes=('_cart', '_event')
    )

    # Keep only history preceding or equal to prediction_timestamp
    history = merged[merged['timestamp'] <= merged['prediction_timestamp']].copy()

    # Determine if the history event is within the current session
    history['is_current_session'] = history['session_id_cart'] == history['session_id_event']

    print("Computing visitor-level and session-level features...")

    # Group by the unique cart unit keys, noting itemid from the cart unit is now named 'itemid_cart'
    group_cols = ['session_id_cart', 'visitorid', 'itemid_cart', 'prediction_timestamp']

    # We want to aggregate statistics from the history subset
    # Let's pivot/aggregate to get various counts
    history['is_view'] = history['event'] == 'view'
    history['is_addtocart'] = history['event'] == 'addtocart'
    history['is_transaction'] = history['event'] == 'transaction'

    # Historical Visitor Features (all history up to prediction_timestamp, including or excluding current session as needed)
    # To make it simple and extremely clean, we calculate total historical events of each type
    visitor_stats = history.groupby(group_cols).agg(
        hist_views=('is_view', 'sum'),
        hist_addtocarts=('is_addtocart', 'sum'),
        hist_transactions=('is_transaction', 'sum'),
        hist_unique_items=('itemid_event', 'nunique')
    ).reset_index()

    # Session-level Features (history within the same session up to the prediction_timestamp)
    session_history = history[history['is_current_session']]
    session_stats = session_history.groupby(group_cols).agg(
        session_views=('is_view', 'sum'),
        session_addtocarts=('is_addtocart', 'sum'),
        session_unique_items=('itemid_event', 'nunique'),
        session_start_time=('timestamp', 'min')
    ).reset_index()

    # Calculate session duration up to prediction_timestamp
    session_stats['session_duration_sec'] = (session_stats['prediction_timestamp'] - session_stats['session_start_time']) / 1000.0
    session_stats = session_stats.drop(columns=['session_start_time'])

    # Merge features back to the labeled dataset
    print("Merging features back to the labeled dataset...")
    final_df = labeled_df.copy()
    final_df = final_df.rename(columns={'session_id': 'session_id_cart', 'itemid': 'itemid_cart'})

    final_df = pd.merge(final_df, visitor_stats, on=group_cols, how='left')
    final_df = pd.merge(final_df, session_stats, on=group_cols, how='left')

    # Fill NaNs with 0 (for cases with no prior history or matching criteria)
    fill_cols = [
        'hist_views', 'hist_addtocarts', 'hist_transactions', 'hist_unique_items',
        'session_views', 'session_addtocarts', 'session_unique_items', 'session_duration_sec'
    ]
    final_df[fill_cols] = final_df[fill_cols].fillna(0)

    # Historical conversion rate
    final_df['hist_conversion_rate'] = (
        final_df['hist_transactions'] / (final_df['hist_addtocarts'] + 1e-5)
    ).clip(0, 1.0)

    # Verify final shape and missing values
    assert len(final_df) == len(labeled_df), "Error: Labeled rows count mismatch!"
    assert not final_df.isnull().any().any(), f"Error: Found NaN values in final engineered features:\n{final_df.isnull().sum()}"

    # Rename columns back to original schema names
    final_df = final_df.rename(columns={'session_id_cart': 'session_id', 'itemid_cart': 'itemid'})

    print(f"Feature engineering complete. final_df shape: {final_df.shape}")
    final_df.to_csv('/content/labeled_units_with_features.csv', index=False)
    return final_df

