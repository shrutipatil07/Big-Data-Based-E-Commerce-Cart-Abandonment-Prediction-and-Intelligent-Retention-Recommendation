import pandas as pd
import numpy as np

def define_cart_abandonment():
    print("=== Starting Phase 5: Define Cart Abandonment Correctly ===")

    # 1. Load sessionized events
    sessionized_path = '/content/sessionized_events.csv'
    print(f"Loading sessionized events from {sessionized_path}...")
    df = pd.read_csv(sessionized_path)

    # 2. Extract qualifying 'addtocart' events to form cart-session units
    addtocart_df = df[df['event'] == 'addtocart'].copy()
    print(f"Found {len(addtocart_df):,} 'addtocart' events.")

    # Identify the earliest addtocart timestamp for each session_id and itemid
    cart_units = addtocart_df.groupby(['session_id', 'visitorid', 'itemid'], as_index=False).agg(
        prediction_timestamp=('timestamp', 'min')
    )
    print(f"Created {len(cart_units):,} unique cart-item session units.")

    # 3. Extract all 'transaction' events to check for conversions
    transactions = df[df['event'] == 'transaction'][['visitorid', 'itemid', 'timestamp']].copy()
    transactions = transactions.rename(columns={'timestamp': 'transaction_timestamp'})

    # 4. Join cart units with transaction records of the same visitor and item
    merged = pd.merge(cart_units, transactions, on=['visitorid', 'itemid'], how='left')

    # Establish observation window: transaction must be after prediction timestamp and within 24 hours
    one_day_ms = 24 * 60 * 60 * 1000  # 86,400,000 ms
    merged['converted'] = (
        (merged['transaction_timestamp'] >= merged['prediction_timestamp']) &
        (merged['transaction_timestamp'] <= merged['prediction_timestamp'] + one_day_ms)
    )

    # If a cart unit has multiple matching transactions, check if any converted
    conversion_status = merged.groupby(['session_id', 'visitorid', 'itemid', 'prediction_timestamp'])['converted'].any().reset_index()

    # 5. Define target label: 0 if converted (not abandoned), 1 if abandoned
    conversion_status['label'] = np.where(conversion_status['converted'], 0, 1)

    # 6. Verification assertions to ensure no data leakage or NaNs
    assert not conversion_status['label'].isnull().any(), "Error: Found NaN values in target labels."

    # Ensure any matching transaction prior to the prediction timestamp is not treated as a conversion
    pre_prediction_conversions = merged[merged['transaction_timestamp'] < merged['prediction_timestamp']]
    if len(pre_prediction_conversions) > 0:
        # Verify that these cases are only labeled as converted (0) if they also had a *valid* transaction later
        for _, row in pre_prediction_conversions.iterrows():
            visitor, item, pred_t = row['visitorid'], row['itemid'], row['prediction_timestamp']
            actual_label = conversion_status[
                (conversion_status['visitorid'] == visitor) &
                (conversion_status['itemid'] == item) &
                (conversion_status['prediction_timestamp'] == pred_t)
            ]['label'].values[0]

            # If there was no transaction in the valid post-prediction window, label must be 1 (abandoned)
            has_valid_post_tx = merged[
                (merged['visitorid'] == visitor) &
                (merged['itemid'] == item) &
                (merged['prediction_timestamp'] == pred_t) &
                (merged['transaction_timestamp'] >= pred_t) &
                (merged['transaction_timestamp'] <= pred_t + one_day_ms)
            ]['converted'].any()

            if not has_valid_post_tx:
                assert actual_label == 1, f"Leakage detected! Pre-prediction transaction used for conversion for visitor {visitor}, item {item}."

    print("Leakage and integrity checks completed successfully.")

    # Output class distribution
    label_counts = conversion_status['label'].value_counts()
    label_pct = conversion_status['label'].value_counts(normalize=True) * 100
    print("\n=== Target Label Distribution ===")
    for label, count in label_counts.items():
        name = "Abandoned (1)" if label == 1 else "Converted (0)"
        print(f"  - {name}: {count:,} ({label_pct[label]:.2f}%)")

    # Save the labeled dataset
    labeled_units_path = '/content/labeled_cart_units.csv'
    conversion_status.to_csv(labeled_units_path, index=False)
    print(f"\nLabeled cart units saved to {labeled_units_path}. Shape: {conversion_status.shape}")
    return conversion_status

