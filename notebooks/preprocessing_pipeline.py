"""**Reasoning**:
Load the cleaned events, calculate temporal gaps between consecutive events per visitor, identify session boundaries using the 30-minute threshold, create unique session IDs, verify boundaries, and save the sessionized events.


"""

import pandas as pd
import numpy as np

def sessionize_events():
    print("=== Starting Phase 4: Sessionization and Gap Analysis ===")

    # 1. Load cleaned events
    cleaned_events_path = '/content/cleaned_events.csv'
    print(f"Loading cleaned events from {cleaned_events_path}...")
    df = pd.read_csv(cleaned_events_path)

    # Ensure sort order: visitorid, then timestamp
    df = df.sort_values(by=['visitorid', 'timestamp']).reset_index(drop=True)

    # 2. Compute temporal gaps (diff) in milliseconds
    # Since we sorted by visitorid and timestamp, we only calculate difference
    # within the same visitor. We can use groupby or shift.
    print("Computing temporal gaps...")
    df['prev_timestamp'] = df.groupby('visitorid')['timestamp'].shift(1)
    df['gap_ms'] = df['timestamp'] - df['prev_timestamp']

    # 3. Define session boundary condition
    # A new session starts if it is the visitor's first event (gap is NaN) or if the gap exceeds 30 minutes (1,800,000 ms)
    threshold_ms = 30 * 60 * 1000  # 1,800,000 ms
    df['new_session_flag'] = (df['gap_ms'].isnull()) | (df['gap_ms'] > threshold_ms)

    # 4. Generate incrementing session index per visitor and unique session_id
    print("Generating unique session IDs...")
    df['session_idx'] = df.groupby('visitorid')['new_session_flag'].cumsum().astype(int)
    df['session_id'] = df['visitorid'].astype(str) + "_" + df['session_idx'].astype(str)

    # 5. Verification / Unit Assertions
    print("Running validation checks...")
    # Check that no session has an internal gap larger than the threshold
    grouped = df.groupby('session_id')
    for sid, group in grouped:
        if len(group) > 1:
            # Calculate gaps within this specific session
            gaps = group['timestamp'].diff().dropna()
            assert (gaps <= threshold_ms).all(), f"Session {sid} has a gap exceeding 30 minutes!"

    print("Assertion passed: All session gaps are within the 30-minute threshold.")

    # Clean up auxiliary columns and save
    df = df.drop(columns=['prev_timestamp', 'gap_ms', 'new_session_flag', 'session_idx'])

    output_path = '/content/sessionized_events.csv'
    df.to_csv(output_path, index=False)
    print(f"Sessionized dataset saved to {output_path}. Shape: {df.shape}\n")
    return df

